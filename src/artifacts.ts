import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { accountsToCsv, importFile } from "./importer.js";
import { issueToMarkdown } from "./issues.js";
import {
  buildDailyReport,
  buildFinalReport,
  buildMaintenanceLog,
  dailyReportToCsv,
  renderDashboard,
} from "./reports.js";
import type { Store } from "./store.js";
import type { HealthCheckResult } from "./types.js";

export interface Paths {
  seed: string;
  actions: string;
  reportsDir: string;
  docsDir: string;
  exportsDir: string;
}

export const DEFAULT_PATHS: Paths = {
  seed: "data/accounts.seed.csv",
  actions: "data/maintenance-actions.json",
  reportsDir: "reports",
  docsDir: "docs",
  exportsDir: "data/exports",
};

/** A human action recorded against an account: onboarding connection or corrective maintenance. */
export interface RecordedAction {
  day: string;
  account_id: string;
  kind: "connect" | "maintenance";
  actor: string;
  detail: string;
  /** Optional pointer to evidence (screenshot path, ticket, etc.). */
  evidence?: string;
}

export function readActions(path: string): RecordedAction[] {
  if (!existsSync(path)) return [];
  return JSON.parse(readFileSync(path, "utf8")) as RecordedAction[];
}

export function appendAction(path: string, action: RecordedAction): void {
  const all = readActions(path);
  all.push(action);
  writeFileSync(path, JSON.stringify(all, null, 2) + "\n");
}

/** Apply one recorded action to the database (idempotence is the caller's concern). */
export function applyAction(store: Store, a: RecordedAction): void {
  const at = `${a.day}T${a.kind === "connect" ? "07:00:00" : "14:30:00"}.000Z`;
  if (a.kind === "connect") {
    const account = store.get(a.account_id);
    if (!account) throw new Error(`cannot connect unknown account ${a.account_id}`);
    if (account.connection_status !== "connected") {
      store.update(a.account_id, { connection_status: "connected" }, a.actor);
    }
  }
  const evidence = a.evidence ? ` [evidence: ${a.evidence}]` : "";
  store.logAction(a.account_id, a.kind, a.actor, `${a.detail}${evidence}`, at);
}

/** Load previously written daily JSON reports back into the database. */
export function loadDailyHistory(store: Store, reportsDir: string): number {
  const dir = join(reportsDir, "daily");
  if (!existsSync(dir)) return 0;
  let n = 0;
  for (const file of readdirSync(dir).filter((f) => /^health-\d{4}-\d{2}-\d{2}\.json$/.test(f)).sort()) {
    const report = JSON.parse(readFileSync(join(dir, file), "utf8")) as { results: HealthCheckResult[] };
    for (const r of report.results) {
      if (store.get(r.account_id)) {
        store.saveHealthCheck(r);
        n++;
      }
    }
  }
  return n;
}

/**
 * The git-tracked files (seed inventory, recorded actions, daily JSON reports)
 * are the source of truth; the SQLite file is a rebuildable working copy.
 * This lets a fresh clone or a stateless CI runner reconstruct full history.
 */
export function rebuildState(store: Store, paths: Paths = DEFAULT_PATHS): { accounts: number; checks: number; actions: number } {
  store.reset();
  importFile(store, paths.seed, "rebuild");
  const actions = readActions(paths.actions);
  for (const a of actions) applyAction(store, a);
  const checks = loadDailyHistory(store, paths.reportsDir);
  return { accounts: store.count(), checks, actions: actions.length };
}

function write(path: string, content: string): string {
  mkdirSync(join(path, ".."), { recursive: true });
  writeFileSync(path, content);
  return path;
}

export function writeDailyReports(store: Store, day: string, paths: Paths = DEFAULT_PATHS): string[] {
  const report = buildDailyReport(store, day);
  const base = join(paths.reportsDir, "daily", `health-${day}`);
  return [
    write(`${base}.json`, JSON.stringify(report, null, 2) + "\n"),
    write(`${base}.csv`, dailyReportToCsv(report)),
  ];
}

/** Regenerate every multi-day artifact: final report, dashboard, issues, maintenance log, inventory export. */
export function writeSummaryArtifacts(store: Store, paths: Paths = DEFAULT_PATHS): string[] {
  const written: string[] = [];
  const final = buildFinalReport(store);
  written.push(write(join(paths.reportsDir, "final-report.json"), JSON.stringify(final, null, 2) + "\n"));
  written.push(write(join(paths.reportsDir, "dashboard.html"), renderDashboard(final)));
  written.push(write(join(paths.docsDir, "maintenance-log.md"), buildMaintenanceLog(store) + "\n"));

  const index: string[] = [
    "# Issue log",
    "",
    "Generated by `qa-accounts report all` from the health-check history. One file per issue.",
    "",
    "| ID | Account | Platform | Code | Severity | First seen | Status |",
    "|---|---|---|---|---|---|---|",
  ];
  for (const issue of final.issues) {
    written.push(write(join(paths.docsDir, "issues", `${issue.id}.md`), issueToMarkdown(issue)));
    index.push(
      `| [${issue.id}](${issue.id}.md) | ${issue.account_id} | ${issue.platform} | \`${issue.code}\` | ${issue.severity} | ${issue.first_seen} | ${issue.status === "open" ? "open" : `resolved ${issue.resolved_on}`} |`
    );
  }
  if (final.issues.length === 0) index.push("| - | - | - | - | - | - | none found |");
  written.push(write(join(paths.docsDir, "issues", "README.md"), index.join("\n") + "\n"));

  const accounts = store.list();
  written.push(write(join(paths.exportsDir, "accounts-inventory.csv"), accountsToCsv(accounts)));
  written.push(write(join(paths.exportsDir, "accounts-inventory.json"), JSON.stringify(accounts, null, 2) + "\n"));
  return written;
}
